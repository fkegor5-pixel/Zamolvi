RULE = ("Стиль общения для этого ответа. Он меняет только тон, а не смысл: отвечай по существу и "
        "не нарушай остальные правила инструкции. ")


def validate(key):
    return key in STYLES


def apply(config, key):
    """The AI settings with the style added to the owner's instruction."""
    instruction = STYLES.get(key or "", STYLES[""])[2]
    if not instruction:
        return config
    return dict(config, prompt=config["prompt"] + "\n\n" + RULE + instruction)


def report(key):
    return {"style": key if key in STYLES else "",
            "styles": [{"key": k, "title": t, "description": d} for k, (t, d, _) in STYLES.items()]}
